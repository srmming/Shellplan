LANGS = ["en", "es", "zh-Hant", "ja"]


def main():
    with open(CATALOG, encoding="utf-8") as f:
        catalog = json.load(f)
    missing = []
    for key, entry in catalog["strings"].items():
        tr = T.get(key)
        if tr is None:
            missing.append(key)
            continue
        if len(tr) == 1:
            tr = tr * 4
        locs = entry.setdefault("localizations", {})
        for lang, value in zip(LANGS, tr):
            if value.count("%") != key.count("%"):
                sys.exit(f"格式符数量不一致：{key!r} → {lang}: {value!r}")
            locs[lang] = {"stringUnit": {"state": "translated", "value": value}}
    with open(CATALOG, "w", encoding="utf-8") as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2, sort_keys=True)
        f.write("\n")
    unused = sorted(set(T) - set(catalog["strings"]))
    print(f"已翻译 {len(catalog['strings']) - len(missing)} / {len(catalog['strings'])}")
    if missing:
        print("还没有翻译：", *missing, sep="\n  ")
    if unused:
        print("翻译表里多余的 key：", *unused, sep="\n  ")


if __name__ == "__main__":
    main()
